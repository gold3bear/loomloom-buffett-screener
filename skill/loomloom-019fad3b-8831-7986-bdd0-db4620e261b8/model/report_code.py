#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Cloud report Code node for the LoomLoom v4 template.

Consumes the cloud audit and model and writes a Markdown artifact. It is gated
on audit.accepted, so a rejected run never produces a report that looks clean.
"""

from __future__ import annotations

import json
from typing import Any, Dict, List, Optional

REPORT_PATH = "report.md"


def _obj(value: Any) -> Dict[str, Any]:
    return value if isinstance(value, dict) else {}


def _text(value: Any) -> str:
    return str(value if value is not None else "").strip()


def _num(value: Any) -> Optional[float]:
    if isinstance(value, bool) or value is None:
        return None
    if isinstance(value, (int, float)):
        return float(value)
    try:
        return float(str(value).replace(",", "").replace("$", ""))
    except ValueError:
        return None


def _money(value: Any) -> str:
    number = _num(value)
    return "—" if number is None else "{:,.2f}".format(number)


def _pct(value: Any) -> str:
    number = _num(value)
    return "—" if number is None else "{:.2f}%".format(number * 100.0)


def _cell(value: Any) -> str:
    return _text(value).replace("|", "\\|").replace("\n", " ")


def _list(items: Any, empty: str = "—") -> str:
    values = [_text(item) for item in items] if isinstance(items, list) else []
    values = [value for value in values if value]
    return "\n".join("- " + value for value in values) if values else "- " + empty


def _dimensions(value: Any) -> str:
    if isinstance(value, dict) and value:
        return "\n".join("- %s: %s" % (key, count) for key, count in value.items())
    return "- no dimension counts"


def _scenario_table(model: Dict[str, Any]) -> str:
    lines = ["| Scenario | Value / share | Equity value | EV | MOS |", "|---|---:|---:|---:|---:|"]
    scenarios = _obj(model.get("scenarios"))
    for name, result in scenarios.items():
        summary = _obj(result.get("summary"))
        lines.append("| %s | %s | %s | %s | %s |" % (_cell(result.get("label") or name), _money(summary.get("valuePerShare")), _money(summary.get("equityValue")), _money(summary.get("enterpriseValue")), _pct(summary.get("marginOfSafetyPct"))))
    return "\n".join(lines)


def render(inputs: Dict[str, Any]) -> str:
    audit = _obj(inputs.get("audit"))
    model = _obj(inputs.get("model"))
    packet, _ = {}, None
    try:
        packet = json.loads(_text(inputs.get("tickerPacket"))) if inputs.get("tickerPacket") else {}
    except ValueError:
        packet = {}
    identity = _obj(packet.get("identityPacket"))
    market = _obj(_obj(packet.get("financialPacket")).get("marketSnapshot"))
    findings = audit.get("findings") if isinstance(audit.get("findings"), list) else []
    errors = [item for item in findings if _obj(item).get("severity") == "error"]
    warnings = [item for item in findings if _obj(item).get("severity") == "warning"]
    ticker = _text(audit.get("ticker")) or _text(identity.get("ticker"))
    lines = [
        "# %s | Cloud Research Report" % (ticker or "US equity"),
        "",
        "> Generated by the LoomLoom v4 cloud pipeline. Research aid only; not investment advice, target price, position size, or buy/sell instruction.",
        "",
        "## Batch summary",
        "",
        "- Cloud audit: **%s**" % ("accepted" if audit.get("accepted") else "rejected"),
        "- Decision tier: %s" % (_text(audit.get("decision")) or "—"),
        "- Overall score: %s/100; confidence: %s" % (_text(audit.get("overall_score")) or "—", _text(audit.get("confidence")) or "—"),
        "- Audit status: %s" % (_text(audit.get("audit_status")) or "—"),
        "- Errors / warnings: %d / %d" % (len(errors), len(warnings)),
        "",
        "| Ticker | Price | Price as of | Model value/share | Model MOS | Evidence |",
        "|---|---:|---|---:|---:|---:|",
        "| %s | %s | %s | %s | %s | %s verified / %s rejected |" % (
            _cell(ticker), _money(market.get("price")), _cell(market.get("asOf")),
            _money(_obj(audit.get("model")).get("valuePerShare")),
            _pct(_obj(audit.get("model")).get("marginOfSafetyPct")),
            _text(_obj(audit.get("evidence")).get("verified")),
            _text(_obj(audit.get("evidence")).get("rejected")),
        ),
        "",
        "## Investment model",
        "",
        "| Scenario | Value / share | Equity value | EV | MOS |",
        "|---|---:|---:|---:|---:|",
    ]
    scenarios = _obj(model.get("scenarios"))
    for name, result in scenarios.items():
        summary = _obj(result.get("summary"))
        lines.append("| %s | %s | %s | %s | %s |" % (_cell(result.get("label") or name), _money(summary.get("valuePerShare")), _money(summary.get("equityValue")), _money(summary.get("enterpriseValue")), _pct(summary.get("marginOfSafetyPct"))))
    base = _obj(scenarios.get(model.get("baseScenario") or "base"))
    summary = _obj(base.get("summary"))
    lines.extend([
        "",
        "- Model status: %s; engine: %s; units: %s" % ("ready" if model.get("model_ready") else "not ready", _text(model.get("engineVersion")), _text(model.get("units"))),
        "- Base value/share: %s; price: %s; MOS: %s" % (_money(summary.get("valuePerShare")), _money(summary.get("price")), _pct(summary.get("marginOfSafetyPct"))),
        "- Enterprise value: %s; equity value: %s; net debt: %s" % (_money(summary.get("enterpriseValue")), _money(summary.get("equityValue")), _money(summary.get("netDebt"))),
        "- Terminal value: %s of EV; reverse DCF implied growth: %s" % (_pct(summary.get("terminalPctOfEv")), _pct(_obj(model.get("reverseDcf")).get("impliedAverageRevenueGrowth"))),
        "",
        "## Evidence",
        "",
        "- Verified: %s; rejected: %s" % (_text(_obj(audit.get("evidence")).get("verified")), _text(_obj(audit.get("evidence")).get("rejected"))),
        _dimensions(_obj(audit.get("evidence")).get("byDimension")),
        "",
        "## Veto items",
        "",
        _list(audit.get("veto_items"), "none"),
        "",
        "## Findings",
        "",
    ])
    if findings:
        for item in findings:
            data = _obj(item)
            lines.append("- `%s` (%s) at `%s`: %s" % (_text(data.get("code")), _text(data.get("severity")), _text(data.get("path")), _text(data.get("message"))))
    else:
        lines.append("- none")
    lines.extend(["", "## Four-dimension summaries", ""])
    for dimension in ("business", "moat", "financial", "valuation"):
        lines.append("### %s" % dimension.title())
        lines.append("")
        lines.append(_text(_obj(audit.get("review_summaries")).get(dimension)) or "—")
        lines.append("")
    lines.extend([
        "## Unknowns",
        "",
        _list(audit.get("unknowns"), "none"),
        "",
        "## Use limits",
        "",
        "The cloud audit checks structure, evidence paths, narrative numbers, scoring and model self-checks. It does not prove that a source is true, that a contract will be delivered, or that a management judgment is correct. Model values are conditional arithmetic on the supplied assumptions.",
        "",
    ])
    return "\n".join(lines)


def main(inputs: Any) -> Dict[str, Any]:
    if not isinstance(inputs, dict):
        inputs = {}
    with open(REPORT_PATH, "w", encoding="utf-8") as handle:
        handle.write(render(inputs))
    return {"report": REPORT_PATH}


if __name__ == "__main__":
    import sys

    print(json.dumps(main(json.load(sys.stdin)), ensure_ascii=False))
